"""Write the wake-prefix word-character table to both runtimes.

The table is every code point whose Unicode general category is a letter (L*)
or number (N*), plus ``_``: Python's ``\\w`` for ``str`` patterns. It is pinned
to one Unicode version because the sidecar's CPython and the extension host's
Node ship different Unicode databases, so ``\\w`` and ``\\p{L}``/``\\p{N}``
disagree on recently assigned code points.

Run from ``python/damocles_voice_sidecar`` with a CPython whose
``unicodedata.unidata_version`` is ``UNICODE_VERSION``:

    uv run python scripts/gen_word_chars.py
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

UNICODE_VERSION = "14.0.0"
LINE_WIDTH = 96

SIDECAR_ROOT = Path(__file__).resolve().parents[1]
PYTHON_OUT = SIDECAR_ROOT / "damocles_voice_sidecar" / "word_chars.py"
TS_OUT = SIDECAR_ROOT.parents[1] / "src" / "shared" / "generated" / "word-chars.ts"


def word_char_ranges() -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    for code in range(sys.maxunicode + 1):
        if code != 0x5F and unicodedata.category(chr(code))[0] not in "LN":
            continue
        if ranges and ranges[-1][1] == code - 1:
            ranges[-1] = (ranges[-1][0], code)
        else:
            ranges.append((code, code))
    return ranges


def range_chunks(ranges: list[tuple[int, int]]) -> list[str]:
    """Space-separated hex ranges, split into lines; every chunk but the last ends in a space."""
    tokens = [f"{a:x}" if a == b else f"{a:x}-{b:x}" for a, b in ranges]
    chunks: list[str] = []
    line = ""
    for token in tokens:
        if line and len(line) + len(token) + 1 > LINE_WIDTH:
            chunks.append(line + " ")
            line = token
        else:
            line = f"{line} {token}" if line else token
    chunks.append(line)
    return chunks


def render_python(chunks: list[str]) -> str:
    body = "".join(f'    "{chunk}"\n' for chunk in chunks)
    return (
        f'"""Generated by scripts/gen_word_chars.py from Unicode {UNICODE_VERSION}; do not edit.\n'
        "\n"
        "Code points that are a Unicode letter or number, or ``_``, as space-separated hex ranges.\n"
        "src/shared/generated/word-chars.ts holds the same table.\n"
        '"""\n'
        "\n"
        f'WORD_CHAR_UNICODE_VERSION = "{UNICODE_VERSION}"\n'
        "\n"
        "WORD_CHAR_RANGES = (\n"
        f"{body}"
        ")\n"
    )


def render_ts(chunks: list[str]) -> str:
    body = " +\n".join(f'  "{chunk}"' for chunk in chunks)
    return (
        "/**\n"
        " * Generated by python/damocles_voice_sidecar/scripts/gen_word_chars.py from Unicode "
        f"{UNICODE_VERSION}; do not edit.\n"
        " *\n"
        " * Code points that are a Unicode letter or number, or `_`, as space-separated hex ranges.\n"
        " * python/damocles_voice_sidecar/damocles_voice_sidecar/word_chars.py holds the same table.\n"
        " */\n"
        "\n"
        f'export const WORD_CHAR_UNICODE_VERSION = "{UNICODE_VERSION}";\n'
        "\n"
        "export const WORD_CHAR_RANGES: string =\n"
        f"{body};\n"
    )


def main() -> int:
    if unicodedata.unidata_version != UNICODE_VERSION:
        print(
            f"needs Unicode {UNICODE_VERSION}; this Python has {unicodedata.unidata_version}",
            file=sys.stderr,
        )
        return 1
    chunks = range_chunks(word_char_ranges())
    PYTHON_OUT.write_text(render_python(chunks), encoding="utf-8")
    TS_OUT.write_text(render_ts(chunks), encoding="utf-8")
    print(f"wrote {PYTHON_OUT} and {TS_OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
