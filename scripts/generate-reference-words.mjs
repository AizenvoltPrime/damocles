// Regenerates the general-vocabulary reference lists the memory injection gate uses to tell ordinary
// words from distinctive tokens (docs/invariants.md "Memory injection"). Commit the output.
//
// English: the lowercase 50k list of david47k/top-english-wordlists at a pinned commit, derived from
// the Google Books Ngram English 1-grams (version 20120701, years 1950 to 2012). Google licenses the
