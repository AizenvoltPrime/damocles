// Software: word lists from Street Side Software's cspell-dicts at a pinned commit
// (@cspell/dict-software-terms and @cspell/dict-filetypes), MIT.
// Each output credits its sources in a `/*!` legal comment, the form esbuild keeps in the minified bundle.
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { porterStem } from '../src/extension/memory/porter-stem.ts';

const ENGLISH_COMMIT = 'b7585f32cee8e140001054ad5b0bbf373245c360';
const ENGLISH_URL = `https://raw.githubusercontent.com/david47k/top-english-wordlists/${ENGLISH_COMMIT}/top_english_words_lower_50000.txt`;
const ENGLISH_SHA256 = 'f9920c664b06b1ce3e94f2a355e11729774329f5838c623cc68e73ebaa374e1b';
const DATASET_URL = 'https://storage.googleapis.com/books/ngrams/books/datasetsv3.html';

const CSPELL_COMMIT = '1d7d9f649f61c9402050a3a56450337bf165c1ba';
const CSPELL_BASE = `https://raw.githubusercontent.com/streetsidesoftware/cspell-dicts/${CSPELL_COMMIT}/dictionaries`;
// The vocabulary files only: identifier lists (POSIX errno and signal names, compound identifiers) and
// the legacy and alternative lists are left out.
const CSPELL_SOURCES = [
  ['software-terms/src/software-terms.txt', '0f51a1e0643f2983634952da8060c864d04a37de9b4dab6230fa0f4971e2b3ca'],
  ['software-terms/src/coding-terms.txt', 'acb533f718cc7c38832c5ddc232d46161a4553b39fc2ba9b63e5bda93976c9b2'],
  ['software-terms/src/computing-acronyms.txt', '5ad1c671d8f9212b6f5c1c169f19f21e480c98b34a763f9f6ed0995ad6d63ff3'],
  ['software-terms/src/software-tools.txt', '494e1dd6d7d5111b45a2fa47ed87c9a94817bcae873e1dce101d1e8995f050f7'],
  ['software-terms/src/software-services.txt', '4125c5bd54e9435111dcb3d9c4f00b2998f391ea6421aac057287e5d23c6ff1f'],
  ['software-terms/src/network-protocols.txt', 'b2b8f0f0cb21dce4b6c26ed8b044dc99b1ebae5e95e85bfff520265e8874f0eb'],
  ['software-terms/src/network-os.txt', '75749b9e90aea3ffaaa51535ad4f3d9b96610f68577cc5ef612a388687ceb9c9'],
  ['software-terms/src/cybersecurity-terms.txt', '3ca4ee0c859532d6f4a142f52b00c9a5fd4249b34d9394587be46cff557b5ea8'],
  ['filetypes/src/filetypes.txt', '9714cb1357d0ff02d5e3f571bc9a3381cbfbee98ef24494cf27d533dec27e2ea'],
];
const CSPELL_PACKAGES = '@cspell/dict-software-terms 5.4.5 and @cspell/dict-filetypes 3.0.18';

const WORDS_PER_LINE = 16;
const OUTPUT_DIR = path.resolve('src/extension/memory/injection');

// Only entries the memory tokenizer yields as one token of 2+ chars can ever be looked up.
const SINGLE_TOKEN = /^[a-z]{2,}$/;

async function download(url, sha256) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Download failed: ${response.status} ${url}`);
  const body = Buffer.from(await response.arrayBuffer());
  const digest = crypto.createHash('sha256').update(body).digest('hex');
  if (digest !== sha256) throw new Error(`Checksum mismatch for ${url}: expected ${sha256}, got ${digest}`);
  return body.toString('utf8');
}

function wrap(words) {
  const lines = [];
  for (let i = 0; i < words.length; i += WORDS_PER_LINE) lines.push(words.slice(i, i + WORDS_PER_LINE).join(' '));
  return lines.join('\n');
}

function write(file, text, count) {
  fs.writeFileSync(path.join(OUTPUT_DIR, file), text);
  console.log(`Wrote ${count} words to ${path.relative(process.cwd(), path.join(OUTPUT_DIR, file))}`);
}

const english = [];
const englishSet = new Set();
for (const line of (await download(ENGLISH_URL, ENGLISH_SHA256)).split(/\r?\n/)) {
  const word = line.trim();
  if (!SINGLE_TOKEN.test(word) || englishSet.has(word)) continue;
  englishSet.add(word);
  english.push(word);
}

// cspell source lines: `word # comment`, `!word` marks a forbidden word, `~word` a case-insensitive variant.
const software = new Set();
for (const [file, sha256] of CSPELL_SOURCES) {
  for (const line of (await download(`${CSPELL_BASE}/${file}`, sha256)).split(/\r?\n/)) {
    const entry = line.replace(/#.*/, '').trim();
    if (entry.startsWith('!')) continue;
    const word = entry.replace(/^~/, '').toLowerCase();
    if (SINGLE_TOKEN.test(word) && !englishSet.has(word)) software.add(word);
  }
}
const softwareWords = [...software].sort();

