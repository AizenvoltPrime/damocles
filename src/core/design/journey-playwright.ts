// A journey as a Playwright test (PD-45), which the implementation replays against the real app. Every value the model
// wrote reaches the source only as a JSON string literal, never in a comment or a template.
import type { JourneyFile, JourneyStep, JourneyTarget } from '../../shared/types/design';
import { RENDER_FRAME_HEIGHT } from '../../shared/design-render';

// JSON.stringify leaves format characters (bidi controls among them) and line and paragraph separators raw; escaped, a reviewer of
// the spec sees the line as it runs, and older parsers never end a string at U+2028 or U+2029.
const literal = (value: string): string => JSON.stringify(value).replace(/[\p{Cf}\p{Zl}\p{Zp}]/gu, (ch) => [...Array(ch.length).keys()].map((at) => `\\u${ch.charCodeAt(at).toString(16).padStart(4, '0')}`).join(''));

// A target without `exact` is exact, so its locator says so; an explicit one is written as it was set.
function locator(target: JourneyTarget): string {
  const exact = `exact: ${target.exact !== false}`;
  if ('role' in target) return `page.getByRole(${literal(target.role)}, { name: ${literal(target.name)}, ${exact} })`;
  if ('label' in target) return `page.getByLabel(${literal(target.label)}, { ${exact} })`;
  if ('placeholder' in target) return `page.getByPlaceholder(${literal(target.placeholder)}, { ${exact} })`;
  return `page.getByText(${literal(target.text)}, { ${exact} })`;
}

// Past any page's height, which Chromium clamps to the scrollable end, as the runner's wheel does.
const WHEEL_TO_END = 'page.mouse.wheel(0, 100000)';

function statement(step: JourneyStep): string {
  if (step.action === 'scroll') {
    if (!step.target) return `await ${WHEEL_TO_END};`;
    const scrolled = locator(step.target);
    // the wheel scrolls the box under the mouse, so it moves over the target first
    return step.to === 'end' ? `await ${scrolled}.scrollIntoViewIfNeeded(); await ${scrolled}.hover(); await ${WHEEL_TO_END};` : `await ${scrolled}.scrollIntoViewIfNeeded();`;
  }
  const element = locator(step.target!);
  switch (step.action) {
    case 'fill':
      return `await ${element}.fill(${literal(step.value!)});`;
    case 'select':
      return `await ${element}.selectOption(${literal(step.value!)});`;
    case 'click':
      return `await ${element}.click();`;
    case 'press':
      return `await ${element}.press(${literal(step.key!)});`;
    case 'assert': {
      const expected = step.expect!;
      if ('visible' in expected) return expected.visible ? `await expect(${element}).toBeVisible();` : `await expect(${element}).toBeHidden();`;
      if ('textContains' in expected) return `await expect(${element}).toContainText(${literal(expected.textContains)});`;
      return `await expect(${element}).toHaveValue(${literal(expected.valueEquals)});`;
    }
  }
}

/** The Playwright test of `journey`: one test per journey width, each a fresh page at that width. */
export function journeyToPlaywright(journey: Pick<JourneyFile, 'screen' | 'state' | 'steps' | 'untested' | 'viewports'>): string {
  const widths = journey.viewports.map((viewport) => viewport.width).filter((width) => Number.isInteger(width));
  return [
    '// Generated by Damocles from the journey JSON beside it; PreviewJourney writes it again, so edits here are lost.',
    '// It replays the design\'s journey against the real app: point SCREEN_URL at the page that implements the screen',
    '// (or set DAMOCLES_JOURNEY_URL) and bring that page to the journey\'s STATE first. It finds controls by role and',
    '// accessible name, so the real controls need the names the design gave them.',
    "import { expect, test } from '@playwright/test';",
    '',
    "const SCREEN_URL = process.env['DAMOCLES_JOURNEY_URL'] ?? '/';",
    `const SCREEN = ${literal(journey.screen)};`,
    `const STATE = ${literal(journey.state)};`,
    `const UNTESTED: readonly string[] = [${journey.untested.map(literal).join(', ')}];`,
    '',
    `for (const width of [${widths.join(', ')}]) {`,
    '  test(`${SCREEN} journey at ${width} px`, async ({ page }) => {',
    "    test.info().annotations.push({ type: 'state', description: STATE }, ...UNTESTED.map((description) => ({ type: 'untested', description })));",
    `    await page.setViewportSize({ width, height: ${RENDER_FRAME_HEIGHT} });`,
    '    await page.goto(SCREEN_URL);',
    ...journey.steps.map((step) => `    ${statement(step)}`),
    '  });',
    '}',
    '',
  ].join('\n');
}
