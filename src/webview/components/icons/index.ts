import { h, type FunctionalComponent, type HTMLAttributes } from "vue";

type IconProps = {
  // Callers use the object and array class forms as well as plain strings, and `h` normalizes all
  // three; typing this as `string` only narrowed what the template was allowed to pass.
  class?: HTMLAttributes["class"];
  style?: HTMLAttributes["style"];
};

function createIcon(pathData: string, viewBox = "0 0 512 512"): FunctionalComponent<IconProps> {
  const component: FunctionalComponent<IconProps> = (props) => {
    return h(
      "svg",
      {
        class: props.class,
        width: 16,
        height: 16,
        viewBox,
        fill: "currentColor",
        xmlns: "http://www.w3.org/2000/svg",
      },
      [h("path", { d: pathData })]
    );
  };
  component.props = ["class"];
  return component;
}

function createMultiPathIcon(paths: string[], viewBox = "0 0 24 24"): FunctionalComponent<IconProps> {
  const component: FunctionalComponent<IconProps> = (props) => {
    return h(
      "svg",
      {
        class: props.class,
        width: 16,
        height: 16,
        viewBox,
        fill: "currentColor",
        fillRule: "evenodd",
        xmlns: "http://www.w3.org/2000/svg",
      },
      paths.map((d) => h("path", { d }))
    );
  };
  component.props = ["class"];
  return component;
}

